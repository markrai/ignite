fn panel_geo() -> FbGeometry {
    let w = PANEL_WIDTH_PX as u32;
    let h = PANEL_HEIGHT_PX as u32;
    FbGeometry {
        xres: w,
        yres: h,
        xres_virtual: w,
        yres_virtual: h,
        xoffset: 0,
        yoffset: 0,
        bits_per_pixel: 8,
        line_length: w,
        smem_len: w * h,
    }
}

fn f(v: f32) -> Value {
    json!(f64::from(v))
}

/// Canonical x, y and optional pressure of one segment endpoint.
type Sample = (f32, f32, Option<f32>);

fn brush_fixture() -> String {
    let curve = PressureCurveV1::sealed_v1();
    let t = ScribeDisplayTransform::PortraitIdentity;

    // Pressure → q → radius, incl. every band boundary and its rounding edges.
    let mut ps: Vec<Option<f32>> =
        vec![None, Some(0.0), Some(1.0), Some(0.5), Some(0.05), Some(0.6)];
    for q in [
        1u16, 819, 820, 821, 2865, 2866, 2867, 3684, 3685, 3686, 4094,
    ] {
        let exact = f32::from(q) / f32::from(PRESSURE_Q_MAX);
        let half = (f32::from(q) + 0.5) / f32::from(PRESSURE_Q_MAX);
        ps.extend([exact, half.next_down(), half, half.next_up()].map(Some));
    }
    let pressure: Vec<Value> = ps
        .iter()
        .map(|p| {
            json!({
                "p": p.map(f),
                "q": p.map(quantize_pressure),
                "radius": curve.radius_for_pressure(*p),
            })
        })
        .collect();

    // Canonical → reference panel pixel (floor + clamp in f32).
    let mut pts: Vec<(f32, f32)> = vec![
        (0.0, 0.0),
        (CANONICAL_PAGE_WIDTH, CANONICAL_PAGE_HEIGHT),
        (8.4, 8.4),
        (8.4f32.next_down(), 8.4f32.next_up()),
        (15_623.99, 20_831.99),
        (7_812.0, 10_416.0),
    ];
    let mut seed = 0x5eed_u64;
    for _ in 0..40 {
        seed = seed
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        let a = ((seed >> 33) as f32 / (1u64 << 31) as f32) * CANONICAL_PAGE_WIDTH;
        seed = seed
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        let b = ((seed >> 33) as f32 / (1u64 << 31) as f32) * CANONICAL_PAGE_HEIGHT;
        pts.push((a.min(CANONICAL_PAGE_WIDTH), b.min(CANONICAL_PAGE_HEIGHT)));
    }
    let panel_pixel: Vec<Value> = pts
        .iter()
        .map(|&(x, y)| {
            let (px, py) = t.to_panel_pixel(PagePoint::new(x, y)).unwrap();
            json!({ "x": f(x), "y": f(y), "px": px, "py": py })
        })
        .collect();

    // Pressure segments: per-step radius from the real Bresenham loop + sealed curve.
    let g = panel_geo();
    let mut buf = vec![0xffu8; g.smem_len as usize];
    let segs: Vec<(Sample, Sample)> = vec![
        ((1000.0, 1000.0, Some(0.05)), (6000.0, 1400.0, Some(0.95))),
        ((6000.0, 1400.0, Some(0.95)), (1000.0, 9000.0, Some(0.30))),
        ((500.0, 500.0, Some(0.6)), (500.0, 500.0, Some(0.9))),
        ((2000.0, 3000.0, Some(0.2)), (2100.0, 3050.0, Some(0.2002))),
        (
            (9000.0, 9000.0, Some(0.7)),
            (15_000.0, 20_000.0, Some(0.71)),
        ),
        ((3000.0, 3000.0, None), (4000.0, 3500.0, Some(0.9))),
        ((3000.0, 3000.0, Some(0.9)), (3300.0, 3900.0, None)),
    ];
    let segments: Vec<Value> = segs
        .iter()
        .map(|&(a, b)| {
            let (x0, y0) = t.to_panel_pixel(PagePoint::new(a.0, a.1)).unwrap();
            let (x1, y1) = t.to_panel_pixel(PagePoint::new(b.0, b.1)).unwrap();
            let both = a.2.is_some() && b.2.is_some();
            let (q0, q1) = (
                a.2.map(quantize_pressure).unwrap_or(0),
                b.2.map(quantize_pressure).unwrap_or(0),
            );
            let mut radii = Vec::new();
            let mut total = 0;
            raster_line_variable_radius(
                &mut buf,
                &g,
                x0 as i32,
                y0 as i32,
                x1 as i32,
                y1 as i32,
                0,
                |step, steps| {
                    total = steps;
                    let r = if both {
                        curve.radius_for_q(interpolate_q(q0, q1, step, steps))
                    } else {
                        curve.missing_fallback_radius
                    };
                    radii.push(r);
                    r
                },
            )
            .unwrap();
            json!({
                "from": { "x": f(a.0), "y": f(a.1), "p": a.2.map(f) },
                "to": { "x": f(b.0), "y": f(b.1), "p": b.2.map(f) },
                "from_px": [x0, y0],
                "to_px": [x1, y1],
                "steps": total,
                "radii": radii,
            })
        })
        .collect();

    let v = json!({
        "v": 1,
        "curve": {
            "q_r1_max": curve.q_r1_max,
            "q_r2_max": curve.q_r2_max,
            "q_r3_max": curve.q_r3_max,
            "min_radius": curve.min_radius,
            "max_radius": curve.max_radius,
            "missing_fallback_radius": curve.missing_fallback_radius,
        },
        "legacy_fixed_radius": LEGACY_FIXED_RADIUS,
        "pressure": pressure,
        "panel_pixel": panel_pixel,
        "segments": segments,
    });
    let mut s = serde_json::to_string_pretty(&v).unwrap();
    s.push('\n');
    s
}

