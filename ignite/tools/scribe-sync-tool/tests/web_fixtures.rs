fn regen() -> bool {
    std::env::var("SCRIBE_REGEN_WEB_FIXTURES").is_ok_and(|v| v == "1")
}

/// Compare (LF-normalized) or rewrite when regenerating.
fn pin_text(path: &Path, want: &str) {
    if regen() {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, want).unwrap();
        return;
    }
    let have = fs::read_to_string(path)
        .unwrap_or_else(|e| {
            panic!(
                "{}: {e} (run with SCRIBE_REGEN_WEB_FIXTURES=1)",
                path.display()
            )
        })
        .replace("\r\n", "\n");
    assert_eq!(
        have,
        want,
        "{} drifted from Rust; regenerate with SCRIBE_REGEN_WEB_FIXTURES=1",
        path.display()
    );
}

