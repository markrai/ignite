//! S3A: Rust-generated fixtures and constants for ignite-web (`ignite/web`).
//!
//! Rust `sync-protocol` is the authoritative wire definition; the TypeScript types are a consumer
//! representation. This test pins everything the browser relies on:
//!
//! * `src/model/generated/protocolConstants.ts`: canonical page space, protocol versions, sealed
//!   render-profile identifiers and the reference raster of the sealed transform (brush units).
//!   Byte-compared on every run: any Rust change fails loudly until regenerated.
//! * `tests/fixtures/brush-v1.json`: pressure → q → radius, canonical → reference-panel pixel,
//!   and per-Bresenham-step radii of pressure segments, computed by the sealed Kindle code
//!   (`pressure_curve`, `ScribeDisplayTransform`, `kindle_platform::raster_line_variable_radius`).
//!   Byte-compared on every run.
//! * `tests/fixtures/snapshot-v1.json` (+ blob + live ops): a real canonical `SyncSnapshotV1`
//!   exported by the Kindle bridge from a library built through the product's durable paths.
//!   IDs are freshly minted, so it is only rewritten with `SCRIBE_REGEN_WEB_FIXTURES=1`; every
//!   run re-validates it strictly and checks its pinned SHA-256 and required features.

