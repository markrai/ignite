fn tmp(label: &str) -> PathBuf {
    let n = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let p = std::env::temp_dir().join(format!("scribe-web-fixture-{label}-{n}"));
    let _ = fs::remove_dir_all(&p);
    p
}

